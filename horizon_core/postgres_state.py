"""PostgreSQL-backed task state for multiple coordinator/worker processes.

Uses psycopg 3, JSONB, dependency foreign keys and row leases selected with
FOR UPDATE SKIP LOCKED. One connection per State instance; each instance serializes
its own connection, while independent workers use separate connections. A schema
is an application namespace, not a tenant security boundary: use a dedicated
agent database/user, never a customer's database credentials. The controller alone
holds this DSN. No default expiry or pruning of memory, checkpoints or events.

This module does not provision infrastructure, configure backups/PITR or assert a
storage capacity. Database backup, retention, encrypted off-site copies and restore
verification must be configured independently. GitHub SQLite snapshots remain
untouched. No automatic migration from them occurs here.
"""
from contextlib import contextmanager
import json
import math
import re
import threading
import time

from .state import LeaseError, _json

try:
    import psycopg
    from psycopg import sql
    from psycopg.rows import dict_row
    from psycopg.types.json import Jsonb
except ImportError:
    psycopg = None


class PostgresStateError(RuntimeError):
    """Configuration/connection error without credentials or raw DSN."""


class PostgresState:
    def __init__(self, dsn, schema='horizon_agents'):
        if not isinstance(schema, str) or not re.fullmatch(r'[a-z][a-z0-9_]{0,62}', schema) or schema.startswith('pg_') or schema in ('public', 'information_schema'):
            raise ValueError('Use a dedicated lowercase application schema')
        if not isinstance(dsn, str) or not dsn.strip():
            raise PostgresStateError('A dedicated agent PostgreSQL DSN is required')
        if psycopg is None:
            raise PostgresStateError('Install requirements-postgres.txt to use PostgreSQL state')
        self.schema = schema
        self._lock = threading.RLock()
        try:
            self.db = psycopg.connect(dsn, autocommit=True, row_factory=dict_row, connect_timeout=15)
        except psycopg.Error:
            raise PostgresStateError('Could not connect to the dedicated agent PostgreSQL database') from None
        try:
            with self._tx():
                # Serialize schema bootstrap across concurrent workers, not task claims.
                self.db.execute('SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))', ('horizon-schema:' + schema,))
                self.db.execute(sql.SQL('CREATE SCHEMA IF NOT EXISTS {}').format(sql.Identifier(schema)))
                self.db.execute(sql.SQL('SET search_path TO {}, pg_catalog').format(sql.Identifier(schema)))
                self.db.execute('''CREATE TABLE IF NOT EXISTS tasks (
                    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    task_id TEXT NOT NULL UNIQUE,
                    agent TEXT NOT NULL, project TEXT NOT NULL, objective TEXT NOT NULL,
                    payload JSONB NOT NULL, depends_on JSONB NOT NULL,
                    status TEXT NOT NULL CHECK(status IN ('queued','running','succeeded','failed','blocked')),
                    priority INTEGER NOT NULL, not_before DOUBLE PRECISION NOT NULL,
                    attempts INTEGER NOT NULL DEFAULT 0 CHECK(attempts >= 0),
                    max_attempts INTEGER NOT NULL CHECK(max_attempts > 0),
                    lease_owner TEXT, lease_until DOUBLE PRECISION,
                    checkpoint JSONB, result JSONB, error JSONB,
                    specification JSONB NOT NULL,
                    CHECK(jsonb_typeof(depends_on) = 'array'),
                    CHECK((status = 'running') = (lease_owner IS NOT NULL AND lease_until IS NOT NULL))
                )''')
                self.db.execute('''CREATE TABLE IF NOT EXISTS task_dependencies (
                    task_id TEXT NOT NULL REFERENCES tasks(task_id),
                    dependency_id TEXT NOT NULL REFERENCES tasks(task_id),
                    PRIMARY KEY(task_id, dependency_id), CHECK(task_id <> dependency_id)
                )''')
                self.db.execute('CREATE INDEX IF NOT EXISTS task_dependencies_reverse ON task_dependencies(dependency_id)')
                self.db.execute("CREATE INDEX IF NOT EXISTS tasks_claim ON tasks(priority DESC, seq) WHERE status='queued'")
                self.db.execute("CREATE INDEX IF NOT EXISTS tasks_expired ON tasks(lease_until) WHERE status='running'")
                self.db.execute('CREATE INDEX IF NOT EXISTS tasks_project ON tasks(project, seq)')
                self.db.execute('''CREATE TABLE IF NOT EXISTS events (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    task_id TEXT NOT NULL REFERENCES tasks(task_id),
                    kind TEXT NOT NULL, data JSONB NOT NULL, created_at DOUBLE PRECISION NOT NULL
                )''')
                self.db.execute('CREATE INDEX IF NOT EXISTS events_task ON events(task_id,id)')
                self.db.execute('''CREATE TABLE IF NOT EXISTS memory (
                    project TEXT NOT NULL, agent TEXT NOT NULL, key TEXT NOT NULL,
                    value JSONB NOT NULL, PRIMARY KEY(project, agent, key)
                )''')
        except BaseException:
            self.db.close()
            raise

    @contextmanager
    def _tx(self):
        with self._lock, self.db.transaction():
            yield

    def close(self):
        with self._lock:
            self.db.close()

    @staticmethod
    def _decode(row):
        if row is None:
            return None
        value = dict(row)
        value.pop('specification', None)
        return value

    @staticmethod
    def _jsonb(value):
        # Reject NaN/Infinity before psycopg serialization and preserve JSON types.
        return Jsonb(json.loads(_json(value)))

    @staticmethod
    def _now(now):
        value = time.time() if now is None else now
        if not isinstance(value, (int, float)) or not math.isfinite(value):
            raise ValueError('A finite timestamp is required')
        return value

    def _event(self, task_id, kind, data, now=None):
        self.db.execute('INSERT INTO events(task_id,kind,data,created_at) VALUES(%s,%s,%s,%s)',
                        (task_id, kind, self._jsonb(data), self._now(now)))

    def enqueue(self, task_id, agent, project, objective, payload=None,
                depends_on=None, priority=0, not_before=0, max_attempts=3):
        if not all(isinstance(value, str) and value.strip() for value in (task_id, agent, project, objective)):
            raise ValueError('task_id, agent, project and objective must be nonempty strings')
        if not isinstance(max_attempts, int) or isinstance(max_attempts, bool) or max_attempts < 1:
            raise ValueError('max_attempts must be positive')
        if depends_on is not None and (not isinstance(depends_on, (list, tuple)) or not all(isinstance(d, str) and d for d in depends_on)):
            raise ValueError('depends_on must contain task IDs')
        deps = sorted(set(depends_on or []))
        if task_id in deps:
            raise ValueError('dependency cycle: task depends on itself')
        payload = {} if payload is None else payload
        specification = json.loads(_json(dict(agent=agent, project=project, objective=objective,
            payload=payload, depends_on=deps, priority=priority, not_before=not_before, max_attempts=max_attempts)))
        with self._tx():
            # Same ID races serialize without a failed INSERT poisoning the transaction.
            self.db.execute('SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))', ('horizon-task:' + task_id,))
            existing = self.db.execute('SELECT * FROM tasks WHERE task_id=%s', (task_id,)).fetchone()
            if existing:
                if existing['specification'] != specification:
                    raise ValueError('task_id already exists with different content')
                return self._decode(existing)
            for dependency in deps:
                if not self.db.execute('SELECT 1 FROM tasks WHERE task_id=%s', (dependency,)).fetchone():
                    raise ValueError('dependency must be enqueued first: ' + dependency)
            row = self.db.execute('''INSERT INTO tasks(task_id,agent,project,objective,payload,depends_on,
                status,priority,not_before,max_attempts,specification)
                VALUES(%s,%s,%s,%s,%s,%s,'queued',%s,%s,%s,%s) RETURNING *''',
                (task_id, agent, project, objective, self._jsonb(payload), self._jsonb(deps), priority,
                 not_before, max_attempts, self._jsonb(specification))).fetchone()
            for dependency in deps:
                self.db.execute('INSERT INTO task_dependencies(task_id,dependency_id) VALUES(%s,%s)', (task_id, dependency))
            self._event(task_id, 'enqueued', {})
            return self._decode(row)

    def claim(self, worker, now=None, lease_seconds=300, project=None):
        now = self._now(now)
        if not isinstance(worker, str) or not worker or lease_seconds <= 0:
            raise ValueError('worker and positive lease_seconds required')
        if project is not None and (not isinstance(project, str) or not project):
            raise ValueError('project filter must be a nonempty string')
        with self._tx():
            expired = self.db.execute("SELECT * FROM tasks WHERE status='running' AND lease_until<=%s FOR UPDATE SKIP LOCKED", (now,)).fetchall()
            for row in expired:
                status = 'failed' if row['attempts'] >= row['max_attempts'] else 'queued'
                self.db.execute('UPDATE tasks SET status=%s,lease_owner=NULL,lease_until=NULL,error=%s WHERE task_id=%s',
                                (status, self._jsonb('lease expired'), row['task_id']))
                self._event(row['task_id'], 'lease_expired', {'status': status}, now)
            # Propagate terminal failures; locked work belongs to another coordinator.
            while True:
                blocked = self.db.execute('''SELECT t.* FROM tasks t WHERE t.status='queued' AND EXISTS (
                    SELECT 1 FROM task_dependencies d JOIN tasks p ON p.task_id=d.dependency_id
                    WHERE d.task_id=t.task_id AND p.status IN ('failed','blocked'))
                    ORDER BY t.seq FOR UPDATE OF t SKIP LOCKED''').fetchall()
                if not blocked:
                    break
                for row in blocked:
                    failures = [r['dependency_id'] for r in self.db.execute('''SELECT d.dependency_id FROM task_dependencies d
                        JOIN tasks p ON p.task_id=d.dependency_id WHERE d.task_id=%s AND p.status IN ('failed','blocked')
                        ORDER BY d.dependency_id''', (row['task_id'],))]
                    self.db.execute("UPDATE tasks SET status='blocked',error=%s WHERE task_id=%s",
                                    (self._jsonb({'failed_dependencies': failures}), row['task_id']))
                    self._event(row['task_id'], 'blocked', {'dependencies': failures}, now)
            ready_sql = '''SELECT t.* FROM tasks t WHERE t.status='queued' AND t.not_before<=%s
                AND NOT EXISTS (SELECT 1 FROM task_dependencies d JOIN tasks p ON p.task_id=d.dependency_id
                    WHERE d.task_id=t.task_id AND p.status<>'succeeded')'''
            ready_args = [now]
            if project is not None:
                ready_sql += ' AND t.project=%s'
                ready_args.append(project)
            ready_sql += ' ORDER BY t.priority DESC,t.seq LIMIT 1 FOR UPDATE OF t SKIP LOCKED'
            row = self.db.execute(ready_sql, ready_args).fetchone()
            if row is None:
                return None
            claimed = self.db.execute("""UPDATE tasks SET status='running',attempts=attempts+1,
                lease_owner=%s,lease_until=%s WHERE task_id=%s RETURNING *""",
                (worker, now + lease_seconds, row['task_id'])).fetchone()
            self._event(row['task_id'], 'claimed', {'worker': worker, 'attempt': claimed['attempts']}, now)
            return self._decode(claimed)

    def _owned(self, task_id, worker, now):
        row = self.db.execute('SELECT * FROM tasks WHERE task_id=%s FOR UPDATE', (task_id,)).fetchone()
        if not row or row['status'] != 'running' or row['lease_owner'] != worker or row['lease_until'] <= now:
            raise LeaseError('worker does not hold an unexpired lease')
        return row

    def renew_lease(self, task_id, worker, lease_seconds=1800, now=None):
        now = self._now(now)
        if lease_seconds <= 0:
            raise ValueError('lease_seconds must be positive')
        with self._tx():
            row = self._owned(task_id, worker, now)
            until = max(row['lease_until'], now + lease_seconds)
            self.db.execute('UPDATE tasks SET lease_until=%s WHERE task_id=%s', (until, task_id))
            self._event(task_id, 'lease_renewed', {'worker': worker, 'lease_until': until}, now)
            return until

    def yield_task(self, task_id, worker, now=None):
        now = self._now(now)
        with self._tx():
            self._owned(task_id, worker, now)
            self.db.execute("""UPDATE tasks SET status='queued',attempts=GREATEST(0,attempts-1),
                lease_owner=NULL,lease_until=NULL,error=NULL,not_before=%s WHERE task_id=%s""", (now, task_id))
            self._event(task_id, 'yielded', {'worker': worker}, now)

    def checkpoint(self, task_id, worker, data, now=None):
        now = self._now(now)
        encoded = self._jsonb(data)
        with self._tx():
            self._owned(task_id, worker, now)
            self.db.execute('UPDATE tasks SET checkpoint=%s WHERE task_id=%s', (encoded, task_id))
            self._event(task_id, 'checkpoint', data, now)

    def complete(self, task_id, worker, result, now=None):
        now = self._now(now)
        encoded = self._jsonb(result)
        with self._tx():
            self._owned(task_id, worker, now)
            self.db.execute("""UPDATE tasks SET status='succeeded',result=%s,error=NULL,
                lease_owner=NULL,lease_until=NULL WHERE task_id=%s""", (encoded, task_id))
            self._event(task_id, 'succeeded', result, now)

    def fail(self, task_id, worker, error, retryable=True, now=None):
        now = self._now(now)
        encoded = self._jsonb(error)
        with self._tx():
            row = self._owned(task_id, worker, now)
            retry = retryable and row['attempts'] < row['max_attempts']
            not_before = now + min(300, 5 * 2 ** min(row['attempts'] - 1, 6)) if retry else row['not_before']
            status = 'queued' if retry else 'failed'
            self.db.execute('''UPDATE tasks SET status=%s,error=%s,not_before=%s,
                lease_owner=NULL,lease_until=NULL WHERE task_id=%s''', (status, encoded, not_before, task_id))
            self._event(task_id, 'retry_scheduled' if retry else 'failed', {'error': error, 'not_before': not_before}, now)

    def remember(self, project, agent, key, value):
        encoded = self._jsonb(value)
        with self._tx():
            self.db.execute('''INSERT INTO memory(project,agent,key,value) VALUES(%s,%s,%s,%s)
                ON CONFLICT(project,agent,key) DO UPDATE SET value=excluded.value''', (project, agent, key, encoded))

    def recall(self, project, agent):
        with self._lock:
            return {row['key']: row['value'] for row in self.db.execute(
                'SELECT key,value FROM memory WHERE project=%s AND agent=%s ORDER BY key', (project, agent))}

    def get(self, task_id):
        with self._lock:
            return self._decode(self.db.execute('SELECT * FROM tasks WHERE task_id=%s', (task_id,)).fetchone())

    def events(self, task_id):
        with self._lock:
            return list(self.db.execute('SELECT * FROM events WHERE task_id=%s ORDER BY id', (task_id,)))

    def tasks(self, project=None):
        with self._lock:
            if project is None:
                rows = self.db.execute('SELECT * FROM tasks ORDER BY seq')
            else:
                rows = self.db.execute('SELECT * FROM tasks WHERE project=%s ORDER BY seq', (project,))
            return [self._decode(row) for row in rows]

    def list_tasks_snapshot(self):
        return [{key: task[key] for key in ('task_id', 'agent', 'status', 'attempts')} for task in self.tasks()]
